_BY_NAME = {k.name: k for k in COMPONENT_KINDS}


def kind(name: str) -> ComponentKind | None:
    return _BY_NAME.get(name)


# Not a creation command -- the other thing the classifier recognizes,
# kept alongside for now. No backing implementation yet (see README's
# "Known gaps") so it isn't a ComponentKind -- there's nothing to draw.

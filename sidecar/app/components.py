"""Registry of component kinds. One place defines, for each kind: what
phrases should classify to it (examples), how Qwen's tool schema should
describe it (description), and how to draw it (an SVG stub).

A stub is inner SVG markup on a 0-100 viewBox, using fill="currentColor" --
it never knows about any particular instance's color. The frontend sets
plain CSS `color` per instance and the SVG inherits it, same trick as any
other currentColor icon.

Adding a new kind is: add one ComponentKind below. Nothing else to touch --
the classifier's example set (`commands`), Qwen's tool schema (tools.py),
and the /components endpoint the frontend renders from are all derived from
this list.
"""

from dataclasses import dataclass


